#!/usr/bin/env python3
"""
METEORFALL texture pipeline.
- Copies/normalizes source textures (web-sourced + AI-generated) into assets/textures
- Creates modified VARIANTS (tint / flip / contrast) as extra asset copies
- Embeds the runtime set as base64 into js/core/EmbeddedTextures.js (origin-clean for file:// WebGL)
"""
import base64
import io
import os
from PIL import Image, ImageEnhance, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "image-search")
TEX = os.path.join(ROOT, "assets", "textures")
OUT_JS = os.path.join(ROOT, "js", "core", "EmbeddedTextures.js")
os.makedirs(TEX, exist_ok=True)
os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)

SIZE = 512


def load_any(path):
    im = Image.open(path)
    if im.mode != "RGB":
        im = im.convert("RGB")
    # center-crop to square then resize
    w, h = im.size
    s = min(w, h)
    im = im.crop(((w - s) // 2, (h - s) // 2, (w + s) // 2, (h + s) // 2))
    return im.resize((SIZE, SIZE), Image.LANCZOS)


def tint(im, rgb, strength=0.35):
    overlay = Image.new("RGB", im.size, rgb)
    return Image.blend(im, overlay, strength)


def adjust(im, brightness=1.0, contrast=1.0, color=1.0):
    if brightness != 1.0:
        im = ImageEnhance.Brightness(im).enhance(brightness)
    if contrast != 1.0:
        im = ImageEnhance.Contrast(im).enhance(contrast)
    if color != 1.0:
        im = ImageEnhance.Color(im).enhance(color)
    return im


def save_jpg(im, name, q=80):
    path = os.path.join(TEX, name)
    im.save(path, "JPEG", quality=q, optimize=True)
    return path


def main():
    sources = {}
    # --- web-sourced (copied from image search, watermark-free picks) ---
    web_grass = os.path.join(SRC, "seamless-grass-texture-tileable-top-down-2.jpg")
    if os.path.exists(web_grass):
        sources["grass"] = load_any(web_grass)
        # keep an untouched copy of the web asset
        save_jpg(sources["grass"], "web_grass_source.jpg", 85)

    # --- AI-generated (clean replacements for watermarked stock previews) ---
    gen = {
        "dirt": "gen_dirt.png",
        "rock": "gen_rock.png",
        "sand": "gen_sand.png",
        "snow": "gen_snow.png",
        "alien": "gen_alien.png",
        "stone": "gen_stone.png",
        "wall": "gen_wall.png",
        "roof": "gen_roof.png",
        "bark": "gen_bark.png",
        "metal": "gen_metal.png",
    }
    for key, fn in gen.items():
        p = os.path.join(TEX, fn)
        if os.path.exists(p):
            sources[key] = load_any(p)

    if "grass" not in sources:
        # last-resort procedural-ish grass from dirt tint
        sources["grass"] = tint(sources["dirt"], (60, 120, 40), 0.6)

    # --- runtime set ---
    runtime = ["grass", "dirt", "rock", "sand", "snow", "alien",
               "wall", "stone", "roof", "wood", "bark", "metal"]

    sources["wood"] = adjust(tint(ImageOps.flip(sources["bark"]), (120, 80, 40), 0.25),
                             brightness=1.1, color=1.1)

    for name in runtime:
        if name in sources:
            save_jpg(sources[name], f"{name}.jpg")

    # --- modified VARIANTS (asset copies with deliberate changes) ---
    variants = {
        "grass_dry.jpg": adjust(tint(sources["grass"], (150, 120, 60), 0.45), color=0.75),
        "grass_swamp.jpg": adjust(tint(sources["grass"], (50, 90, 60), 0.5), brightness=0.8),
        "rock_dark.jpg": adjust(tint(sources["rock"], (40, 40, 55), 0.4), brightness=0.7),
        "sand_wet.jpg": adjust(tint(sources["sand"], (90, 80, 60), 0.35), brightness=0.85),
        "alien_warm.jpg": adjust(tint(sources["alien"], (150, 80, 20), 0.3), color=1.2),
        "wall_scorched.jpg": adjust(tint(sources["wall"], (30, 25, 25), 0.45), brightness=0.65),
        "stone_mossy.jpg": adjust(tint(sources["stone"], (60, 110, 60), 0.28), brightness=0.95),
        "metal_rusty.jpg": adjust(tint(sources["metal"], (120, 60, 30), 0.35), contrast=1.1),
    }
    for fn, im in variants.items():
        save_jpg(im, fn)

    # --- embed runtime set as base64 ---
    chunks = ["// AUTO-GENERATED by tools/build_textures.py — embedded texture pack\n",
              "// (base64 JPEG data-URIs are origin-clean even on file:// pages)\n",
              "window.MF_TEXTURES = {\n"]
    total = 0
    for name in runtime:
        path = os.path.join(TEX, f"{name}.jpg")
        if not os.path.exists(path):
            continue
        with open(path, "rb") as f:
            data = f.read()
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        chunks.append(f'  "{name}": "data:image/jpeg;base64,{b64}",\n')
    chunks.append("};\n")
    with open(OUT_JS, "w") as f:
        f.write("".join(chunks))
    print(f"Embedded {len(runtime)} textures, raw {total/1024:.0f} KB -> {OUT_JS}")
    print(f"Variants written: {len(variants)}")
    for fn in sorted(os.listdir(TEX)):
        p = os.path.join(TEX, fn)
        print(f"  {fn:24s} {os.path.getsize(p)/1024:7.1f} KB")


if __name__ == "__main__":
    main()
